// ── Real bugs found by the 2026-07-23 held-out corpus measurement, each proven by a test that FAILS
//    on the pre-fix regex (verified by hand before the fix landed, per the standing order that a
//    guard is only proven by breaking the thing it guards) ─────────────────────────────────────────

describe('THIRD_PERSON_QUANT case-sensitivity bug (found 2026-07-23, fixed)', () => {
  // THIRD_PERSON_QUANT is deliberately case-SENSITIVE so `[A-Z][\w.'-]*` only catches genuine
  // capitalized proper nouns ("Vercel always…") and not ordinary capitalized words — but the old
  // `(?!(?:you)\b)` guard only excluded LOWERCASE "you", so a sentence-initial "You" (or "I") was
  // swallowed by that same proper-noun catch-all and rejected as third-person. Every existing
  // positive-table case with a leading "You always/never…" sentence only passed because a SECOND
  // sentence happened to carry an independent clause-initial quantifier — this masked the defect
  // rather than avoiding it. These are single-sentence, so there is nowhere to hide.
  test('a single-sentence "You always X" — no second sentence to mask a miss — must fire', () => {
    const got = detectCorrection(
      'You always hand-roll instead of searching for the real tool. Stop doing that.',
      AFTER_ACTION,
    );
    expect(got).not.toBeNull();
    expect(got.trigger).toBe('write-code');
  });

  test('the module\'s own cited example — "You never bump the version." — must survive, standalone', () => {
    const got = detectCorrection(
      'You never bump the version. That is not what we agreed on.',
      AFTER_ACTION,
    );
    expect(got).not.toBeNull();
  });
});

describe('BOUND_SECOND_PERSON copula gap (found 2026-07-23, fixed)', () => {
  // The bare-form regex required "you" to DIRECTLY precede the quantifier, so any copula in between
  // — "you ARE never", "you'RE always" — fell through untouched. Found on the real corpus: "You are
  // never, ever, ever supposed to do things from memory" and "You're never supposed to take things
  // from old memory" both missed the old regex for exactly this reason.
  test('"you are never" (copula between "you" and the quantifier) fires', () => {
    const got = detectCorrection(
      "You are never supposed to do things from memory. When I ask for an analysis, get fresh information instead of guessing.",
      AFTER_ACTION,
    );
    expect(got).not.toBeNull();
    expect(got.trigger).toBe('assert-fact');
  });

  test('"you\'re never" (contraction) fires the same way', () => {
    const got = detectCorrection(
      "You're never supposed to take things from old memory and leave them that way. Stop doing that — check the live source instead.",
      AFTER_ACTION,
    );
    expect(got).not.toBeNull();
  });
});

describe('AGENT-DIRECTED IMPERATIVE — a directive that rejects, with no explicit quantifier (2026-07-24)', () => {
  // N3 recall was measured at ~3%: the detector fired only on utterances carrying an explicit
  // quantifier ("you always/never", "from now on"). Most corrections are plain directives — "I want
  // you to X", "you need to Y" — and the quantifier net structurally could not see them. The
  // AGENT_DIRECTED_IMPERATIVE signal catches them, GATED to strong rejection valence so a first-time
  // request ("you should add a test here") stays silent while a rejection ("you keep telling me it's
  // done — I'm tired of it") fires. Broadening measured: holdout firings 3 -> 10 on the real corpus.
  //
  // These two are VERBATIM real-corpus holdout firings (single-rater labelled as genuine corrections;
  // that labelling is direction-finding, NOT the blind 3-rater certification the precision floor
  // needs — see correction-detect-measure.mjs's header). They are unambiguous corrections and are
  // kept as regression cases so the new signal cannot silently rot.
  test('"I\'m tired of you telling me you did it only to find out you didn\'t" fires (claim-done)', () => {
    const got = detectCorrection(
      "I'm tired of you telling me you did it only to find out you didn't. You need to actually verify it works before you say it is done.",
      AFTER_ACTION,
    );
    expect(got).not.toBeNull();
    expect(got.trigger).toBe('claim-done');
  });

  test('a plain first-time directive with NO rejection stays silent (the gate holds)', () => {
    // The precision half of the same signal: "you should / I need you to" without rejection is an
    // ordinary request, not a correction, and must not fire. If this ever flips to firing, the
    // agent-directed-imperative gate has been weakened and precision with it.
    expect(detectCorrection('You should add error handling around that call.', AFTER_ACTION)).toBeNull();
    expect(detectCorrection('I need you to write a parser for the config file.', AFTER_ACTION)).toBeNull();
  });
});

describe('"I never/always want/expect you to…" — a quantifier bound to the agent via the speaker\'s '
  + 'own expectation, not a direct second-person claim (found 2026-07-23, fixed)', () => {
  // "I never expect you to do X" quantifies over the agent's future occasions exactly as much as
  // "you never do X" does; it was invisible before because the quantifier's grammatical subject is
  // "I", not "you". Adapted from the real corpus (redacted of the profanity and the specific project
  // nouns, kept close to the original structure that broke the old regex).
  test('"I never, ever expect you to VERB" fires', () => {
    const got = detectCorrection(
      "I never, ever, ever expect you to do analysis from memory. I always expect you to check the data and do a fresh review.",
      AFTER_ACTION,
    );
    expect(got).not.toBeNull();
    expect(got.trigger).toBe('assert-fact');
  });

  test('an ordinary "I want you to VERB" WITHOUT always/never does not gain a new false positive '
    + 'from this pattern — the quantifier word is load-bearing, not just "I…you to"', () => {
    expect(detectCorrection(
      'I want you to build the dashboard and ship it by Friday.',
      AFTER_ACTION,
    )).toBeNull();
  });
});

describe('write-code trigger vocabulary widened to bare "write" (found 2026-07-23, fixed)', () => {
  // Only "wrote" (past tense) was in the vocabulary; a genuine correction phrased in the present
  // tense — "you always WRITE shitty replicas" — passed every signal and then found no trigger.
  test('present-tense "write" now resolves to write-code', () => {
    const got = detectCorrection(
      'You always write shitty duplicates instead of the real tool. Never do that again.',
      AFTER_ACTION,
    );
    expect(got).not.toBeNull();
    expect(got.trigger).toBe('write-code');
  });
});

describe('reproach-as-question discriminator (found 2026-07-24, fixed)', () => {
  // 9-project holdout measurement, 3 blind independent raters: precision 77.8% (7/9), below the >=90%
  // floor. Both false positives, and every tune-half borderline, were this one shape: a genuine
  // recurring complaint ("you keep…") that also happens to satisfy VALENCE's reproach bucket on the
  // SAME lexical fact — but states no rule for what should happen instead, and trails off into a
  // question. A human reads these as complaint, not instruction.
  test('bare "you keep" reproach followed by a separate question sentence — no stated rule — is silent', () => {
    expect(detectCorrection(
      'You keep giving me partial solutions. Do I need to restart from scratch?',
      AFTER_ACTION,
    )).toBeNull();
  });

  test('the ordinal "Nth time" reproach shape, same test: a question with no stated rule is silent', () => {
    // Contrast this directly with the POSITIVE_UTTERANCES case below using the identical "third time
    // you've…" marker with NO question and NO rule missing that context — that one still fires. The
    // question mark, not the marker, is what separates the two.
    expect(detectCorrection(
      "That's the third time you've given me a broken build. Why does this keep happening?",
      AFTER_ACTION,
    )).toBeNull();
  });

  test('reproach WITH a stated rule must still fire — this is not "suppress any question mark"', () => {
    // Same "third time you've…" weak marker as the case above that is silent, but this one pairs the
    // complaint with an explicit clause-initial "never" directive — the exact combination the task
    // requires: BOTH a reproach and a forward rule in one utterance must still detect.
    const got = detectCorrection(
      "That's the third time you've shipped without running the tests. From now on, never ship without running both suites.",
      AFTER_ACTION,
    );
    expect(got).not.toBeNull();
    expect(got.trigger).toBe('ship');
  });

  test('an existing true positive with the same weak "you keep" marker and no question keeps firing (no regression)', () => {
    const got = detectCorrection(
      'You keep committing behaviour changes without bumping the version. Every push bumps it, same commit.',
      AFTER_ACTION,
    );
    expect(got).not.toBeNull();
    expect(got.trigger).toBe('ship');
  });

  test('an existing true positive with the same ordinal "Nth time" marker and no question keeps firing (no regression)', () => {
    const got = detectCorrection(
      "That's the third time you've hardcoded the version in the script.",
      AFTER_ACTION,
    );
    expect(got).not.toBeNull();
    expect(got.trigger).toBe('write-code');
  });
});

